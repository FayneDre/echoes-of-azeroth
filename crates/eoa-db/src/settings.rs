use std::path::Path;

/// Server options of an instance. Defaults favour performance and durability,
/// never minimal resource use (CLAUDE.md principle 2).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ServerSettings {
    /// TCP port on `127.0.0.1`.
    pub port: u16,
    /// InnoDB buffer pool. The world database is ~1 GB once imported; 1 GiB keeps
    /// the hot set in memory.
    pub buffer_pool_mib: u32,
    /// Redo log capacity. Larger = much faster bulk imports (dbimport, restores).
    pub redo_log_capacity_mib: u32,
    pub max_connections: u32,
}

impl Default for ServerSettings {
    fn default() -> Self {
        Self {
            port: 3306,
            buffer_pool_mib: 1024,
            redo_log_capacity_mib: 512,
            max_connections: 200,
        }
    }
}

impl ServerSettings {
    /// Renders `my.ini`. Paths use forward slashes: backslashes are escape
    /// characters in MySQL option files.
    pub(crate) fn render(&self, basedir: &Path, datadir: &Path, log: &Path) -> String {
        let slash = |p: &Path| p.to_string_lossy().replace('\\', "/");
        format!(
            "\
# Generated by Echoes of Azeroth. Edits are overwritten: change settings in the launcher.
[mysqld]
basedir=\"{basedir}\"
datadir=\"{datadir}\"
log-error=\"{log}\"
port={port}
# Private to this computer; LAN players reach the game servers, never MySQL.
bind-address=127.0.0.1
# One instance per realm: no X Protocol port (33060) to collide with others.
mysqlx=OFF
# No replication: binary logs would only cost disk space and import speed.
disable-log-bin
character-set-server=utf8mb4
collation-server=utf8mb4_unicode_ci
max_connections={max_connections}
innodb_buffer_pool_size={buffer_pool}M
innodb_redo_log_capacity={redo}M
# Durability first: player data must survive a power cut.
innodb_flush_log_at_trx_commit=1
",
            basedir = slash(basedir),
            datadir = slash(datadir),
            log = slash(log),
            port = self.port,
            max_connections = self.max_connections,
            buffer_pool = self.buffer_pool_mib,
            redo = self.redo_log_capacity_mib,
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_forward_slash_paths_and_safe_defaults() {
        let ini = ServerSettings {
            port: 3310,
            ..Default::default()
        }
        .render(
            Path::new(r"C:\Apps\mysql"),
            Path::new(r"C:\Inst\data"),
            Path::new(r"C:\Inst\mysqld.log"),
        );
        assert!(ini.contains("basedir=\"C:/Apps/mysql\"\n"));
        assert!(ini.contains("datadir=\"C:/Inst/data\"\n"));
        assert!(ini.contains("port=3310\n"));
        assert!(ini.contains("bind-address=127.0.0.1\n"));
        assert!(ini.contains("mysqlx=OFF\n"));
        assert!(ini.contains("innodb_flush_log_at_trx_commit=1\n"));
        assert!(!ini.contains('\\'));
    }
}
